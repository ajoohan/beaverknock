/* DB 가 거절한 이유를 사람 말로 바꾼다.
 *
 * 지금까지 저장이 실패하면 화면에는 '저장하지 못했습니다' 한 줄만 떴다.
 * 그것만으로는 **무엇을 고쳐야 하는지 알 수 없어서**, 원인을 보려면 매번
 * 브라우저 콘솔을 열어 detail 을 읽어야 했다. 손님에게도 우리에게도 나쁘다.
 *
 * PostgREST 는 거절할 때 SQLSTATE 를 함께 준다. 그 코드는 스키마 사정을
 * 드러내지 않으면서(칸 이름도 값도 들어 있지 않다) 무엇이 문제인지는 분명히
 * 가리킨다 - 그래서 코드만 뽑아 쓴다.
 *
 * ⚠ 칸 이름이 들어 있는 message 는 여기서 쓰지 않는다. 그건 로그에만 남긴다.
 */

/* 실제로 마주칠 만한 것만 적는다. 없는 코드는 일반 문구로 떨어진다 -
   모르는 것을 아는 척하는 문구가 제일 나쁘다. */
const WHY = {
  '22003': '금액이 너무 큽니다 - 자릿수를 다시 확인해 주세요',
  '22001': '적어주신 내용이 너무 깁니다 - 조금 줄여 주세요',
  '22P02': '숫자를 적는 칸에 숫자가 아닌 값이 들어 있습니다',
  '22007': '날짜 형식이 맞지 않습니다',
  '23502': '필수 항목이 비어 있습니다',
  '23503': '연결된 정보를 찾지 못했습니다',
  '23505': '이미 접수된 내용입니다',
  '23514': '입력값이 허용 범위를 벗어났습니다',
  '42501': '권한이 없어 저장하지 못했습니다',
};

/* PostgREST 응답 본문에서 코드와 사람 말을 뽑는다.
   본문이 JSON 이 아니어도(프록시가 HTML 을 돌려주는 경우 등) 터지지 않는다. */
export function dbWhy(text) {
  let code = null;
  try {
    const j = JSON.parse(String(text || ''));
    if (j && typeof j.code === 'string') code = j.code;
  } catch (e) { /* JSON 이 아니면 코드는 없는 것으로 둔다 */ }
  return { code, msg: (code && WHY[code]) || null };
}
