/* 밴드와 연식 — 손님이 고른 칸과 물건의 숫자를 잇는 자리.
   여기가 한 칸 어긋나면 **경계에 있는 물건이 통째로 사라지거나**,
   맞지 않는 물건이 '맞음' 으로 올라간다. 둘 다 조용히 일어난다.
   (2026-09-24 에 bandtest 35건이 임시 폴더 청소로 사라져 다시 썼다) */
import * as 길 from './길.mjs';

const js = 길.js();
/* 밴드 선언 덩어리를 통째로 꺼내 쓴다 - 화면을 안 띄우고 그대로 재려면 이 길뿐이다 */
const 잘라 = (a, b) => { const i = js.indexOf(a), j = js.indexOf(b, i); return js.slice(i, j); };
/* 덩어리 안의 LMUSTS 가 바깥의 MUSTS 를 쓴다 - 그것까지 같이 들고 온다.
   (통째로 eval 하면 화면 코드가 document 를 찾아 터지므로 선언만 잘라 쓴다) */
const src = 잘라('const MUSTS', '/* ── 손님이 고르는 밴드')
          + 잘라('const HAREA = [', 'const FLOORS=');
const M = new Function(`${src}
  return {HAREA,HBATH,HFLOOR,HAGE,bandOf,ageOf,homeFloorBand,shopBandOf,
          DIRS,DIR_BASE,FEE_BASIS,FEE_TYPE,MOVEIN,LPARK,NO_BLDG_NAME};`)();

let ran = 0, fail = 0;
const ok = (c, m) => { ran++; console.log((c ? '  OK  ' : '  X   ') + m); if(!c) fail++; };
const eq = (got, want, m) => ok(JSON.stringify(got) === JSON.stringify(want),
  `${m} → ${JSON.stringify(got)}${JSON.stringify(got) === JSON.stringify(want) ? '' : ` (${JSON.stringify(want)} 여야 한다)`}`);

/* ── 면적 밴드 ── 경계는 **아래를 포함하고 위를 뺀다**(lo ≤ x < hi).
   33㎡ 가 '~33㎡' 와 '33~66㎡' 양쪽에 들면 같은 물건이 두 밴드로 읽힌다. */
const A = v => (M.bandOf(M.HAREA, v) || {}).t ?? null;
eq(A(0),     '~33㎡',    '면적 0㎡');
eq(A(32.9),  '~33㎡',    '면적 32.9㎡');
eq(A(33),    '33~66㎡',  '면적 33㎡ - 경계는 위 밴드로');
eq(A(59.94), '33~66㎡',  '면적 59.94㎡');
eq(A(66),    '66~99㎡',  '면적 66㎡ - 경계');
eq(A(131.9), '99~132㎡', '면적 131.9㎡');
eq(A(132),   '132㎡~',   '면적 132㎡ - 경계');
eq(A(99999), '132㎡~',   '아주 큰 면적도 마지막 밴드에 든다');
ok(M.HAREA.every((b, i, a) => i === 0 || b.lo === a[i-1].hi),
   '면적 밴드에 틈이 없다 - 앞 밴드의 끝이 다음 밴드의 시작이다');

/* 숫자가 아니면 **아무 말도 하지 않는다.** 0 으로 읽어 '~33㎡' 라고 하면
   비어 있는 물건이 작은 집으로 둔갑한다. */
eq(A(null),  null, '면적이 비면 밴드를 말하지 않는다');
eq(A(''),    null, '면적이 빈 글자면 말하지 않는다');
eq(A('가'),  null, '면적이 글자면 말하지 않는다');
eq(A(-5),    null, '음수 면적은 어느 밴드에도 안 든다');

/* ── 연식 ── 사용승인일은 자유 형식이다(2016.06.24 · 2016-06 · 2016년). */
const 올해 = new Date().getFullYear();
eq(M.ageOf(`${올해}.01.01`), 0,  '올해 지은 것은 0년차');
eq(M.ageOf(`${올해 - 10}`),  10, '10년 전');
eq(M.ageOf('2016.06.24'), 올해 - 2016, '2016.06.24');
eq(M.ageOf('2016-06'),    올해 - 2016, '2016-06 (붙임표)');
eq(M.ageOf('2016년 6월'), 올해 - 2016, '2016년 6월 (한글)');
eq(M.ageOf(''),        null, '비었으면 연식을 말하지 않는다');
eq(M.ageOf(null),      null, '없으면 말하지 않는다');
eq(M.ageOf('모름'),    null, '연도가 없으면 말하지 않는다');
eq(M.ageOf(`${올해 + 5}`), null, '앞으로 지을 것은 음수라 말하지 않는다');

const G = v => (M.bandOf(M.HAGE, v) || {}).t ?? null;
eq(G(0),  '5년 이내', '0년차');
eq(G(5),  '5~10년',   '5년차 - 경계는 위 밴드로');
eq(G(20), '20년~',    '20년차 - 경계');
eq(G(60), '20년~',    '아주 오래된 것도 마지막 밴드');
ok(M.HAGE.every((b, i, a) => i === 0 || b.lo === a[i-1].hi), '연식 밴드에 틈이 없다');

/* ── 주거 층 밴드 ── 중개사는 정확한 층을 적고 손님은 저·중·고로 고른다. */
const F = (floorNo, floors, band) => M.homeFloorBand({ floorNo, floors, band });
eq(F('1'),      '1층',  '1층');
eq(F('3'),      '저층', '3층');
eq(F('4'),      '중층', '4층');
eq(F('8'),      '중층', '8층');
eq(F('9'),      '고층', '9층');
eq(F('15', 15), '탑층', '15층 / 총 15층 - 탑층');
eq(F('14', 15), '고층', '14층 / 총 15층 - 아직 탑층이 아니다');
/* 총 층수를 모르면 탑층인지 알 수 없다 - 모르면 말하지 않는다 */
eq(F('15'),     '고층', '15층 / 총 층수 모름 - 탑층이라고 하지 않는다');
/* 지하는 주거 밴드에 없다. 억지로 '1층' 이라고 하면 반지하가 1층으로 올라간다. */
eq(F('B1'),  '', '지하 1층 - 주거 밴드에 없다');
eq(F('-1'),  '', '-1층');
eq(F('지하'), '', '지하');
eq(F('b2'),  '', '소문자 b2 도 지하다');
/* 층을 안 적었으면 중개사가 고른 고·중·저를 그대로 쓴다 */
eq(F('', 0, '중층'),   '중층', '층을 안 적었으면 고른 밴드를 쓴다');
eq(F('꼭대기', 0, '고층'), '고층', '숫자가 아니면 고른 밴드를 쓴다');
eq(F(''),              '',     '둘 다 없으면 말하지 않는다');

/* ── 상가 층 ── 상가는 고·중·저 칸이 없어서 적어둔 층에서 유도한다. */
eq(M.shopBandOf('1'),    '1층만',       '상가 1층');
eq(M.shopBandOf('2'),    '2층 이상 가능', '상가 2층');
eq(M.shopBandOf('10'),   '2층 이상 가능', '상가 10층');
eq(M.shopBandOf('B1'),   '지하 가능',    '상가 지하');
eq(M.shopBandOf('-1'),   '지하 가능',    '상가 -1층');
eq(M.shopBandOf(''),     '',            '안 적었으면 말하지 않는다');
eq(M.shopBandOf('반'),   '',            '숫자가 아니면 말하지 않는다');

/* ── 표시·광고 명시사항의 보기들 ──
   법이 요구하는 칸이라 **보기를 줄이면 적을 수 없는 경우가 생긴다.** */
ok(M.DIRS.length === 8,      `방향 8가지 - ${M.DIRS.join('·')}`);
ok(M.DIR_BASE.length === 3 && M.DIR_BASE.every(x => x.endsWith('기준')),
   `방향 기준 3가지, 전부 '기준' 으로 끝난다`);
ok(M.FEE_BASIS.includes('표시하지 않음'), "관리비 기준에 '표시하지 않음' 이 있다 - 모르면 모른다고 적을 수 있어야 한다");
ok(M.FEE_TYPE.includes('확인불가'),       "관리비 부과방식에 '확인불가' 가 있다");
ok(M.MOVEIN.includes('날짜 지정'),        "입주 시기에 '날짜 지정' 이 있다");
eq(M.LPARK, ['가능','불가'],             "상가 주차는 가능·불가 둘뿐 ('문의' 는 안 고르는 것이 곧 문의다)");

/* ── 건물명이 없는 것이 정상인 유형 ── 억지로 적게 하면 지번이나 사람 이름이 들어간다 */
ok(M.NO_BLDG_NAME('단독·다가구'), '단독·다가구는 건물명이 없어도 된다');
ok(M.NO_BLDG_NAME('상가주택'),    '상가주택은 건물명이 없어도 된다');
ok(!M.NO_BLDG_NAME('아파트'),     '아파트는 건물명이 있어야 한다');
ok(!M.NO_BLDG_NAME(''),           '빈 유형은 면제가 아니다');

console.log(`${ran} 통과 / ${fail} 실패`.replace(`${ran} 통과`, `${ran - fail} 통과`));
process.exit(fail ? 1 : 0);
